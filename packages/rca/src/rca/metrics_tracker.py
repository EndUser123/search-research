            cursor = conn.execute(
                """
                SELECT
                    r.problem_hash,
                    r.problem_type,
                    COUNT(r.recurred_at) as recurrence_count,
                    MAX(s.started_at) as first_seen,
                    MAX(r.recurred_at) as last_recurrence
                FROM rca_recurrences r
                JOIN rca_sessions s ON r.original_problem_hash = s.problem_hash
                WHERE r.recurred_at > ?
                GROUP BY r.problem_hash
                ORDER BY recurrence_count DESC
                LIMIT ?
            """,
                (cutoff, limit),
            )

            results = []
            for row in cursor.fetchall():
                results.append(
                    {
                        "problem_hash": row[0],
                        "problem_type": row[1],
                        "recurrence_count": row[2],
                        "first_seen": row[3],
                        "last_recurrence": row[4],
                    }
                )

