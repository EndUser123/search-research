@dataclass
class BudgetStatus:
    """Status of session budget tracking."""
    status: str  # "OK", "WARN", "HALT"
    tokens_used: int
    tokens_remaining: int
    budget_pct: float
    reason: str = ""
    action: str = ""


class SessionBudget:
    """
    Cost Circuit Breaker for RCA/debug sessions.

    Tracks token usage across a session and halts when budget exceeded
    or max retries reached. Prevents runaway LLM costs during debugging.

    Example:
        budget = SessionBudget(max_tokens=100_000, max_retries=3)
        budget_check = budget.add_tokens(5000)
        if budget_check.status == "HALT":
            return "Budget exceeded, escalate to human"
    """

    # Approximate token cost: $2.00 ≈ 100,000 tokens at current rates
    DEFAULT_MAX_TOKENS = 100_000
    DEFAULT_MAX_RETRIES = 3

    def __init__(
        self,
        max_tokens: int = DEFAULT_MAX_TOKENS,
        max_retries: int = DEFAULT_MAX_RETRIES
    ):
        """
        Initialize session budget.

        Args:
            max_tokens: Maximum tokens allowed per session (≈$2.00)
            max_retries: Maximum retry attempts before escalation
        """
        self.max_tokens = max_tokens
        self.max_retries = max_retries
        self.session_tokens = 0
        self.retry_count = 0
        self.halted = False
        self.halt_reason = None

    def add_tokens(self, input_tokens: int, output_tokens: int) -> BudgetStatus:
        """
        Track tokens from an LLM interaction.

        Args:
            input_tokens: Input tokens sent to LLM
            output_tokens: Output tokens received from LLM

        Returns:
            BudgetStatus with current state
        """
        if self.halted:
            return BudgetStatus(
                status="HALT",
                tokens_used=self.session_tokens,
                tokens_remaining=0,
                budget_pct=100.0,
                reason=self.halt_reason,
                action="Session already halted - escalate to human"
            )

        total_tokens = input_tokens + output_tokens
        self.session_tokens += total_tokens
        remaining = self.max_tokens - self.session_tokens
        budget_pct = (self.session_tokens / self.max_tokens) * 100

        # Check if budget exceeded
        if remaining < 0:
            self.halted = True
            self.halt_reason = "Budget exceeded"
            return BudgetStatus(
                status="HALT",
                tokens_used=self.session_tokens,
                tokens_remaining=0,
                budget_pct=100.0,
                reason="Budget exceeded",
                action=f"Escalate to human - used {self.session_tokens:,} tokens"
            )

        # Warning at 80% budget
        if budget_pct >= 80:
            return BudgetStatus(
                status="WARN",
                tokens_used=self.session_tokens,
                tokens_remaining=remaining,
                budget_pct=budget_pct,
                reason="Approaching budget limit",
                action=f"Consider escalation - {budget_pct:.1f}% budget used"
            )

        return BudgetStatus(
            status="OK",
            tokens_used=self.session_tokens,
            tokens_remaining=remaining,
            budget_pct=budget_pct
        )

    def increment_retry(self) -> BudgetStatus:
        """
        Track a retry attempt.

        Returns:
            BudgetStatus with current state
        """
        if self.halted:
            return BudgetStatus(
                status="HALT",
                tokens_used=self.session_tokens,
                tokens_remaining=self.max_tokens - self.session_tokens,
                budget_pct=(self.session_tokens / self.max_tokens) * 100,
                reason=self.halt_reason,
                action="Session already halted"
            )

        self.retry_count += 1
        remaining_retries = self.max_retries - self.retry_count

        # Check if max retries exceeded
        if self.retry_count > self.max_retries:
            self.halted = True
            self.halt_reason = "Max retries exceeded"
            return BudgetStatus(
                status="HALT",
                tokens_used=self.session_tokens,
                tokens_remaining=self.max_tokens - self.session_tokens,
                budget_pct=(self.session_tokens / self.max_tokens) * 100,
                reason="Max retries exceeded",
                action="Problem too complex - escalate to human developer"
            )

        # Warning at last retry
        if remaining_retries == 0:
            return BudgetStatus(
                status="WARN",
                tokens_used=self.session_tokens,
                tokens_remaining=self.max_tokens - self.session_tokens,
                budget_pct=(self.session_tokens / self.max_tokens) * 100,
                reason="Last retry",
                action="Final attempt - consider escalation if this fails"
            )

        return BudgetStatus(
            status="OK",
            tokens_used=self.session_tokens,
            tokens_remaining=self.max_tokens - self.session_tokens,
            budget_pct=(self.session_tokens / self.max_tokens) * 100
        )

    def get_summary(self) -> dict:
        """Get summary of current budget state."""
        return {
            "tokens_used": self.session_tokens,
            "tokens_remaining": max(0, self.max_tokens - self.session_tokens),
            "budget_pct": (self.session_tokens / self.max_tokens) * 100,
            "retries_used": self.retry_count,
            "retries_remaining": max(0, self.max_retries - self.retry_count),
            "halted": self.halted,
            "halt_reason": self.halt_reason
        }

    def reset(self) -> None:
        """Reset budget tracking (use with caution)."""
        self.session_tokens = 0
        self.retry_count = 0
        self.halted = False
        self.halt_reason = None


