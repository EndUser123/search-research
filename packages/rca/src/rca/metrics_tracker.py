def enforce_verification_gate(
    session_id: str,
    files_changed: list[str],
    bug_type: str = "unknown",
    auto_run: bool = True
) -> dict[str, Any]:
    """
    Enforce the verification gate - fix MUST pass verification to be complete.

    This is the REQUIRED verification step for all fixes in the /debug workflow.

    Args:
        session_id: The RCA session ID
        files_changed: List of files that were modified
        bug_type: Type of bug (error, performance, crash, etc.)
        auto_run: If True, automatically run the verification command

    Returns:
        Dict with verification result and gate status

    Raises:
        Exception: If verification fails and auto_run is True

    """
    import importlib.util
    import subprocess
    import sys
    from pathlib import Path

    # Load post_fix_validator module directly via importlib
    hooks_dir = Path(str(Path(__file__).drive) + "/.claude/hooks")
    validator_path = hooks_dir / "post_fix_validator.py"

    if not validator_path.exists():
        return {
            "success": False,
            "error": "post_fix_validator not found",
            "gate_passed": False,
            "message": f"Verification gate cannot be enforced: {validator_path} not found"
        }

    try:
        # Load module from file path
        spec = importlib.util.spec_from_file_location("post_fix_validator", validator_path)
        if spec is None or spec.loader is None:
            raise ImportError(f"Cannot load module from {validator_path}")
        validator_module = importlib.util.module_from_spec(spec)
        sys.modules["post_fix_validator"] = validator_module
        spec.loader.exec_module(validator_module)

        suggest_fix_verification = validator_module.suggest_fix_verification
        run_fix_verification = validator_module.run_fix_verification
    except (ImportError, AttributeError) as e:
        return {
            "success": False,
            "error": f"post_fix_validator import failed: {e}",
            "gate_passed": False,
            "message": "Verification gate cannot be enforced"
        }

    # Get verification suggestion
    suggestion = suggest_fix_verification(files_changed, bug_type)

    result = {
        "session_id": session_id,
        "files_changed": files_changed,
        "suggested_command": suggestion.get("command"),
        "gate_passed": False,
        "verification_run": False,
    }

    if auto_run and suggestion.get("command"):
        print(f"🔍 Running verification: {suggestion['command']}")

        try:
            verify_result = run_fix_verification(
                suggestion["command"],
                timeout=60 if suggestion.get("estimated_runtime") == "medium" else 30
            )

            result["verification_run"] = True
            result["verification_output"] = verify_result.get("stdout", "")
            result["verification_error"] = verify_result.get("stderr", "")

            if verify_result["success"]:
                result["gate_passed"] = True
                result["success"] = True
                record_verification(session_id, passed=True)
                print("✅ VERIFICATION PASSED - Fix gate cleared")
                return result
            result["success"] = False
            result["error"] = "Verification command failed"
            record_verification(session_id, passed=False)

            error_msg = f"""❌ VERIFICATION GATE FAILED
Command: {suggestion['command']}
Exit code: {verify_result.get('exit_code')}
Output: {verify_result.get('stdout', '')[:200]}
"""
            print(error_msg)
            raise Exception("Verification gate failed - fix not verified")

        except subprocess.TimeoutExpired:
            result["success"] = False
            result["error"] = "Verification timed out"
            record_verification(session_id, passed=False)
            raise Exception("Verification timed out")
    else:
        result["message"] = "Verification gate pending - run command manually"
        result["suggestion"] = suggestion
        return result

    return result


