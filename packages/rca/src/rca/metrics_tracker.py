@dataclass
class MetricAlert:
    """An alert for a metric threshold breach."""

    metric_name: str
    current_value: float
    threshold: float
    severity: str  # "warning", "critical"
    message: str
    action_suggestion: str


class MetricThresholds:
    """
    Threshold definitions for RCA metrics with automated alerts.

    When thresholds are breached, triggers actionable alerts.
    """

    # Threshold format: (warning_level, critical_level, lower_is_better)
    THRESHOLDS = {
        "chs_usage_rate": (90, 80, False),  # Below 90% = warning, below 80% = critical
        "quick_fix_success_rate": (85, 70, False),  # Below 85% = warning
        "fix_verification_rate": (95, 80, False),  # Below 95% = warning
        "recurrence_rate_7d": (8, 15, True),  # Above 8% = warning, above 15% = critical
        "recurrence_rate_30d": (15, 25, True),  # Above 15% = warning
        "avg_time_exact_match": (3, 5, True),  # Above 3min = warning
        "avg_time_new_issue": (12, 20, True),  # Above 12min = warning
        "chs_hit_rate": (50, 40, False),  # Below 50% = warning
    }

    @classmethod
    def check_thresholds(cls, metrics: RCAMetrics) -> list[MetricAlert]:
        """
        Check metrics against thresholds and generate alerts.

        Args:
            metrics: Current metrics to check

        Returns:
            List of MetricAlert for any breached thresholds

        """
        alerts = []

        # Check each metric
        metric_values = {
            "chs_usage_rate": metrics.chs_usage_rate,
            "quick_fix_success_rate": metrics.quick_fix_success_rate,
            "fix_verification_rate": metrics.fix_verification_rate,
            "recurrence_rate_7d": metrics.recurrence_rate_7d,
            "recurrence_rate_30d": metrics.recurrence_rate_30d,
            "avg_time_exact_match": metrics.avg_time_exact_match,
            "avg_time_new_issue": metrics.avg_time_new_issue,
            "chs_hit_rate": metrics.chs_hit_rate,
        }

        for metric_name, value in metric_values.items():
            if metric_name not in cls.THRESHOLDS:
                continue

            warning_thresh, critical_thresh, lower_is_better = cls.THRESHOLDS[metric_name]

            # Determine if threshold is breached
            if lower_is_better:
                # Lower is better (e.g., recurrence rate, time)
                if value >= critical_thresh:
                    alerts.append(MetricAlert(
                        metric_name=metric_name,
                        current_value=value,
                        threshold=critical_thresh,
                        severity="critical",
                        message=f"{metric_name}: {value} (threshold: <{critical_thresh})",
                        action_suggestion=cls._get_action_suggestion(metric_name, "critical")
                    ))
                elif value >= warning_thresh:
                    alerts.append(MetricAlert(
                        metric_name=metric_name,
                        current_value=value,
                        threshold=warning_thresh,
                        severity="warning",
                        message=f"{metric_name}: {value} (threshold: <{warning_thresh})",
                        action_suggestion=cls._get_action_suggestion(metric_name, "warning")
                    ))
            # Higher is better (e.g., success rate, hit rate)
            elif value <= critical_thresh:
                alerts.append(MetricAlert(
                    metric_name=metric_name,
                    current_value=value,
                    threshold=critical_thresh,
                    severity="critical",
                    message=f"{metric_name}: {value}% (threshold: >{critical_thresh}%)",
                    action_suggestion=cls._get_action_suggestion(metric_name, "critical")
                ))
            elif value <= warning_thresh:
                alerts.append(MetricAlert(
                    metric_name=metric_name,
                    current_value=value,
                    threshold=warning_thresh,
                    severity="warning",
                    message=f"{metric_name}: {value}% (threshold: >{warning_thresh}%)",
                    action_suggestion=cls._get_action_suggestion(metric_name, "warning")
                ))

        return alerts

    @classmethod
    def _get_action_suggestion(cls, metric_name: str, severity: str) -> str:
        """Get action suggestion for a metric breach."""
        suggestions = {
            "chs_usage_rate": "CHS not being used consistently - enforce CHS-first policy in /debug workflow",
            "quick_fix_success_rate": "Error signatures may be outdated - refresh pattern database from recent fixes",
            "fix_verification_rate": "Fixes not being verified - enforce test run before marking fix complete",
            "recurrence_rate_7d": "PROBLEMS RECURRING - fixes addressing symptoms not root causes. Use deeper RCA.",
            "recurrence_rate_30d": "High recurrence indicates systemic issues - review fix quality and root cause analysis",
            "avg_time_exact_match": "Quick fixes taking too long - improve error signature matching",
            "avg_time_new_issue": "RCA slow - consider specialist subagent routing for faster resolution",
            "chs_hit_rate": "Historical search not finding matches - may need more indexing or better queries",
        }

        base = suggestions.get(metric_name, "Review this metric for process improvement")

        if severity == "critical":
            return f"🚨 CRITICAL: {base}"
        return f"⚠️ WARNING: {base}"


