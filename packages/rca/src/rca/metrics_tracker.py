def format_alerts(alerts: list[MetricAlert]) -> str:
    """
    Format metric alerts for display.

    Args:
        alerts: List of MetricAlert

    Returns:
        Formatted alert string

    """
    if not alerts:
        return "✅ All metrics within normal thresholds."

    lines = ["🚨 METRIC ALERTS DETECTED:\n"]

    # Critical alerts first
    critical = [a for a in alerts if a.severity == "critical"]
    warnings = [a for a in alerts if a.severity == "warning"]

    if critical:
        lines.append("## CRITICAL:")
        for alert in critical:
            lines.append(f"  ❌ {alert.message}")
            lines.append(f"     → {alert.action_suggestion}")
        lines.append("")

    if warnings:
        lines.append("## WARNINGS:")
        for alert in warnings:
            lines.append(f"  ⚠️ {alert.message}")
            lines.append(f"     → {alert.action_suggestion}")

    return "\n".join(lines)


